export function makeItem(name: string): Canvas {
  const rows = ITEM_GRIDS[name];
  if (!rows) throw new Error('Unknown item ' + name);
  const cv = new Canvas(16, 16);
  rows.forEach((row, y) => {
    [...row].forEach((ch, x) => {
      if (ch !== '.') cv.set(x, y, hx(PAL[ch]!));
    });
  });
  return cv;
}
